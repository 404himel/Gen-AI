def get_generation_model():
    if "evaluator_llm" in globals():
        return evaluator_llm
    if "llm" in globals():
        return llm
    raise ValueError("No LLM pipeline found. Define llm or evaluator_llm first.")


def generate_high_band_answers(question, part, item_type="Question", number_of_answers=3):
    generator = get_generation_model()
    high_band_answers = []

    for index in range(number_of_answers):
        prompt = f"""
You are an IELTS Speaking candidate with a high band level.

Write one natural high band sample answer for this IELTS Speaking item.

Target band:
{7 + index}

Part:
{part}

Item type:
{item_type}

Question:
{question}

Rules:
Return only the answer.
Do not explain.
Use natural spoken English.
Do not repeat the same idea as a previous sample.
Make the answer clear, organized, and relevant.
For Part 1, answer in 3 to 5 sentences.
For Part 2, give a developed long turn answer.
For Part 3, give a developed discussion answer with reasons and examples.

High Band Answer:
"""

        try:
            result = generator(
                prompt,
                max_new_tokens=320,
                do_sample=True,
                temperature=0.55,
                top_p=0.9,
                return_full_text=False
            )

            answer = safe_text(result[0]["generated_text"])

            if count_words(answer) >= 8:
                high_band_answers.append({
                    "target_band": 7 + index,
                    "answer": answer
                })

        except:
            pass

    if len(high_band_answers) == 0:
        high_band_answers.append({
            "target_band": 8,
            "answer": "This is a clear, organized, and developed answer with relevant explanation and examples."
        })

    return high_band_answers


def save_high_band_answers(reference_items, file_path="ielts_high_band_reference_answers.txt"):
    with open(file_path, "w", encoding="utf-8") as f:
        f.write("IELTS High Band Reference Answers\n")
        f.write("=" * 70 + "\n\n")

        for item in reference_items:
            f.write(f"Part: {item['part']}\n")
            f.write(f"Item Type: {item['item_type']}\n")
            f.write(f"Question: {item['question']}\n\n")

            for answer in item["high_band_answers"]:
                f.write(f"Target Band: {answer['target_band']}\n")
                f.write(answer["answer"] + "\n\n")

            f.write("=" * 70 + "\n\n")

    print("High band answers saved:", file_path)


