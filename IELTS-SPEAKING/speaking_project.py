def normalize_question(question):
    question = str(question).lower().strip()
    question = question.replace("?", "")
    question = re.sub(r"[^a-z0-9\s]", "", question)
    question = re.sub(r"\s+", " ", question)
    return question


def clean_question(text):
    text = str(text).strip()
    text = text.replace('"', "")
    text = text.replace("Question:", "").strip()

    lines = text.split("\n")
    text = lines[0].strip()

    if "?" in text:
        text = text.split("?")[0].strip() + "?"

    if len(text) < 5:
        return None

    if "?" not in text:
        return None

    bad_phrases = [
        "here is",
        "sure",
        "ielts",
        "part 1",
        "examiner",
        "candidate",
        "generate"
    ]

    lower_text = text.lower()

    for phrase in bad_phrases:
        if phrase in lower_text:
            return None

    return text


def is_duplicate_question(new_question, used_questions):
    new_clean = normalize_question(new_question)

    for old_question in used_questions:
        old_clean = normalize_question(old_question)

        if new_clean == old_clean:
            return True

        if new_clean in old_clean:
            return True

        if old_clean in new_clean:
            return True

        new_words = set(new_clean.split())
        old_words = set(old_clean.split())

        if len(new_words) > 0 and len(old_words) > 0:
            overlap = len(new_words.intersection(old_words))
            similarity = overlap / max(len(new_words), len(old_words))

            if similarity >= 0.70:
                return True

    return False


def get_unused_fallback_question(question_number, used_questions):
    if question_number <= 4:
        fallback_pool = easy_fallback_questions.copy()
    else:
        fallback_pool = medium_fallback_questions.copy()

    random.shuffle(fallback_pool)

    for fallback_question in fallback_pool:
        if not is_duplicate_question(fallback_question, used_questions):
            return fallback_question

    all_fallbacks = easy_fallback_questions + medium_fallback_questions
    random.shuffle(all_fallbacks)

    for fallback_question in all_fallbacks:
        if not is_duplicate_question(fallback_question, used_questions):
            return fallback_question

    return None


def generate_part1_question(question_number, used_questions=None):
    if used_questions is None:
        used_questions = []

    if question_number <= 4:
        topic_pool = easy_topics.copy()
        difficulty_note = "The question should be very simple and personal."
    else:
        topic_pool = medium_topics.copy()
        difficulty_note = "The question should be slightly harder but still suitable for IELTS Speaking Part 1."

    random.shuffle(topic_pool)

    previous_questions_text = ""

    if len(used_questions) > 0:
        previous_questions_text = "\n".join(
            [f"{index + 1}. {question}" for index, question in enumerate(used_questions)]
        )
    else:
        previous_questions_text = "None"

    for topic in topic_pool:
        prompt = f"""
You are an IELTS Speaking examiner.

Generate exactly one IELTS Speaking Part 1 question about {topic}.

Rules:
Return only one question.
Do not ask multiple questions.
Do not explain anything.
The question must be natural.
The question must be short.
Do not repeat any previous question.
Do not closely rephrase any previous question.
{difficulty_note}

Previous questions:
{previous_questions_text}

Question:
"""

        for attempt in range(3):
            result = llm(
                prompt,
                max_new_tokens=40,
                do_sample=True,
                temperature=0.75,
                top_p=0.95
            )

            generated_text = result[0]["generated_text"]
            question = generated_text[len(prompt):].strip()
            question = clean_question(question)

            if question is not None:
                if not is_duplicate_question(question, used_questions):
                    return question

    fallback_question = get_unused_fallback_question(question_number, used_questions)

    if fallback_question is not None:
        return fallback_question

    return None

