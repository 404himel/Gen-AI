def structure_features(answer_text):
    text = safe_text(answer_text).lower()

    explanation_markers = [
        "because",
        "as",
        "since",
        "the reason",
        "this is why",
        "due to"
    ]

    example_markers = [
        "for example",
        "for instance",
        "such as",
        "in my case",
        "one example"
    ]

    contrast_markers = [
        "however",
        "but",
        "although",
        "on the other hand",
        "whereas"
    ]

    sequence_markers = [
        "first",
        "second",
        "then",
        "after that",
        "finally",
        "overall"
    ]

    return {
        "has_clear_answer": 1 if count_words(answer_text) >= 8 else 0,
        "has_explanation": 1 if any(m in text for m in explanation_markers) else 0,
        "has_example": 1 if any(m in text for m in example_markers) else 0,
        "has_contrast": 1 if any(m in text for m in contrast_markers) else 0,
        "has_sequence": 1 if any(m in text for m in sequence_markers) else 0
    }


def structure_similarity(user_answer, reference_answer):
    user_features = structure_features(user_answer)
    reference_features = structure_features(reference_answer)

    matches = 0
    possible = 0

    for key in reference_features:
        if reference_features[key] == 1:
            possible += 1
            if user_features[key] == 1:
                matches += 1

    if possible == 0:
        return 0.5

    return round(matches / possible, 3)


def lexical_metrics(user_answer, reference_answers):
    words = clean_text_for_words(user_answer)

    if len(words) == 0:
        return {
            "type_token_ratio": 0.0,
            "advanced_word_ratio": 0.0,
            "best_semantic_similarity": 0.0,
            "lexical_similarity_score": 0.0
        }

    unique_words = set(words)
    type_token_ratio = len(unique_words) / len(words)

    advanced_words = []

    for word in words:
        if len(word) >= 7:
            frequency = zipf_frequency(word, "en")
            if frequency > 0 and frequency <= 4.5:
                advanced_words.append(word)

    advanced_word_ratio = len(advanced_words) / len(words)

    similarities = []

    for reference in reference_answers:
        similarities.append(
            semantic_similarity(user_answer, reference["answer"])
        )

    best_similarity = max(similarities) if len(similarities) > 0 else 0.0

    type_token_component = min(type_token_ratio / 0.65, 1.0)
    advanced_component = min(advanced_word_ratio / 0.16, 1.0)

    lexical_similarity_score = (
        0.4 * type_token_component +
        0.3 * advanced_component +
        0.3 * best_similarity
    )

    return {
        "type_token_ratio": round(type_token_ratio, 3),
        "advanced_word_ratio": round(advanced_word_ratio, 3),
        "best_semantic_similarity": round(best_similarity, 3),
        "lexical_similarity_score": round(lexical_similarity_score, 3)
    }


def grammar_metrics(user_answer):
    words = count_words(user_answer)

    if words == 0:
        return {
            "grammar_error_count": 0,
            "grammar_error_rate": 1.0,
            "structure_complexity": 0.0,
            "grammar_formula_score": 0.0
        }

    errors = grammar_error_count(user_answer)
    error_rate = errors / max(words, 1)

    sentences = re.split(r"[.!?]+", safe_text(user_answer))
    sentences = [s.strip() for s in sentences if s.strip() != ""]

    avg_sentence_length = words / max(len(sentences), 1)

    subordinators = [
        "because",
        "although",
        "while",
        "whereas",
        "which",
        "that",
        "who",
        "when",
        "if",
        "since",
        "after",
        "before"
    ]

    lower_text = safe_text(user_answer).lower()
    subordinator_count = sum(lower_text.count(s) for s in subordinators)

    length_component = min(avg_sentence_length / 18, 1.0)
    subordinator_component = min(subordinator_count / 4, 1.0)

    structure_complexity = (
        0.6 * length_component +
        0.4 * subordinator_component
    )

    accuracy_component = 1.0 - min(error_rate / 0.15, 1.0)

    grammar_formula_score = (
        0.5 * accuracy_component +
        0.5 * structure_complexity
    )

    return {
        "grammar_error_count": errors,
        "grammar_error_rate": round(error_rate, 3),
        "structure_complexity": round(structure_complexity, 3),
        "grammar_formula_score": round(grammar_formula_score, 3)
    }


def fluency_formula_score(audio_features, user_answer, reference_answers):
    words_per_second = audio_features.get("words_per_second", 0.0)
    silent_ratio = audio_features.get("silent_ratio", 1.0)
    pause_count = audio_features.get("pause_count", 0)
    filler_count = audio_features.get("filler_count", 0)
    speech_ratio = audio_features.get("speech_ratio", 0.0)

    speech_rate_score = min(words_per_second / 2.4, 1.0)
    pause_score = 1.0 - min(pause_count / 12, 1.0)
    silence_score = 1.0 - min(silent_ratio / 0.45, 1.0)
    filler_score = 1.0 - min(filler_count / 8, 1.0)

    reference_structure_scores = []

    for reference in reference_answers:
        reference_structure_scores.append(
            structure_similarity(user_answer, reference["answer"])
        )

    best_structure_score = max(reference_structure_scores) if len(reference_structure_scores) > 0 else 0.0

    fluency_score = (
        0.30 * speech_rate_score +
        0.25 * pause_score +
        0.20 * silence_score +
        0.10 * filler_score +
        0.15 * best_structure_score
    )

    coherence_score = best_structure_score

    combined_score = (
        0.6 * fluency_score +
        0.4 * coherence_score
    )

    return {
        "speech_rate_score": round(speech_rate_score, 3),
        "pause_score": round(pause_score, 3),
        "silence_score": round(silence_score, 3),
        "filler_score": round(filler_score, 3),
        "best_structure_score": round(best_structure_score, 3),
        "fluency_formula_score": round(combined_score, 3)
    }


def pronunciation_formula_score(audio_features):
    speech_ratio = audio_features.get("speech_ratio", 0.0)
    silent_ratio = audio_features.get("silent_ratio", 1.0)
    clarity_proxy = audio_features.get("clarity_proxy", 0.0)
    pause_count = audio_features.get("pause_count", 0)
    words_per_second = audio_features.get("words_per_second", 0.0)

    speech_continuity = speech_ratio
    silence_component = 1.0 - min(silent_ratio / 0.50, 1.0)
    pause_component = 1.0 - min(pause_count / 14, 1.0)

    rhythm_component = 0.0

    if 1.2 <= words_per_second <= 2.8:
        rhythm_component = 1.0
    elif 0.8 <= words_per_second < 1.2:
        rhythm_component = 0.65
    elif 2.8 < words_per_second <= 3.3:
        rhythm_component = 0.65
    else:
        rhythm_component = 0.35

    pronunciation_score = (
        0.30 * clarity_proxy +
        0.25 * speech_continuity +
        0.20 * silence_component +
        0.15 * rhythm_component +
        0.10 * pause_component
    )

    return {
        "clarity_proxy": round(clarity_proxy, 3),
        "speech_continuity": round(speech_continuity, 3),
        "silence_component": round(silence_component, 3),
        "rhythm_component": round(rhythm_component, 3),
        "pause_component": round(pause_component, 3),
        "pronunciation_formula_score": round(pronunciation_score, 3)
    }


