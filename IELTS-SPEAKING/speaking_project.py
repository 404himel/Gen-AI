# Evidence Band Cap
# ============================================================

def calculate_evidence_band_cap(global_features, enriched_items):
    total_answers = global_features.get("total_answers", 0)
    total_words = global_features.get("total_words", 0)
    empty_answer_count = global_features.get("empty_answer_count", 0)
    short_answer_count = global_features.get("short_answer_count", 0)
    total_duration = global_features.get("total_speaking_duration_seconds", 0)
    average_wpm = global_features.get("average_words_per_minute", 0)
    silent_ratio = global_features.get("average_silent_ratio", 1.0)

    cap = 9.0
    reasons = []

    if total_answers == 0:
        return 0.0, ["No answers were available."]

    if empty_answer_count >= 1:
        cap = min(cap, 5.0)
        reasons.append("At least one answer was empty.")

    if empty_answer_count >= total_answers:
        cap = min(cap, 1.0)
        reasons.append("All answers were empty.")

    if short_answer_count >= 1:
        cap = min(cap, 5.5)
        reasons.append("At least one answer was very short.")

    if total_words < 30:
        cap = min(cap, 3.5)
        reasons.append("Total spoken content was extremely limited.")
    elif total_words < 60:
        cap = min(cap, 4.5)
        reasons.append("Total spoken content was limited.")
    elif total_words < 100:
        cap = min(cap, 5.5)
        reasons.append("Total spoken content was not enough for a high band.")

    if total_duration < 30:
        cap = min(cap, 4.0)
        reasons.append("Total speaking duration was too short.")
    elif total_duration < 60:
        cap = min(cap, 5.5)
        reasons.append("Total speaking duration was limited.")

    if average_wpm > 0 and average_wpm < 70:
        cap = min(cap, 5.5)
        reasons.append("Speech rate was low.")

    if silent_ratio >= 0.30:
        cap = min(cap, 5.5)
        reasons.append("Silent portion was high.")

    for item in enriched_items:
        if item.get("part") == "Part 2" and item.get("item_type") == "Cue Card":
            word_count = item.get("word_count", 0)
            duration = item.get("audio_features", {}).get("duration_seconds", 0)

            if word_count < 40:
                cap = min(cap, 4.0)
                reasons.append("The Part 2 long turn was too short.")
            elif word_count < 80:
                cap = min(cap, 5.0)
                reasons.append("The Part 2 long turn was underdeveloped.")

            if duration < 45:
                cap = min(cap, 4.5)
                reasons.append("The Part 2 speaking time was too short.")

    return round(cap, 1), reasons


