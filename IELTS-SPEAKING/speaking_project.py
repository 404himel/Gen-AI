def build_advanced_global_features(enriched_items):
    total_answers = len(enriched_items)
    total_words = 0
    total_duration = 0.0
    empty_answer_count = 0
    short_answer_count = 0

    fluency_scores = []
    lexical_scores = []
    grammar_scores = []
    pronunciation_scores = []

    total_pause_count = 0
    total_filler_count = 0
    total_repetition_count = 0
    silent_ratios = []
    speech_ratios = []
    wpms = []

    for item in enriched_items:
        total_words += item["word_count"]

        if item["is_empty_answer"]:
            empty_answer_count += 1

        if item["word_count"] < 10:
            short_answer_count += 1

        audio_features = item["audio_features"]
        total_duration += audio_features.get("duration_seconds", 0.0)
        total_pause_count += audio_features.get("pause_count", 0)
        total_filler_count += audio_features.get("filler_count", 0)
        total_repetition_count += audio_features.get("repetition_count", 0)

        silent_ratios.append(audio_features.get("silent_ratio", 1.0))
        speech_ratios.append(audio_features.get("speech_ratio", 0.0))

        if audio_features.get("words_per_minute", 0) > 0:
            wpms.append(audio_features.get("words_per_minute", 0))

        fluency_scores.append(item["fluency_metrics"]["fluency_formula_score"])
        lexical_scores.append(item["lexical_metrics"]["lexical_similarity_score"])
        grammar_scores.append(item["grammar_metrics"]["grammar_formula_score"])
        pronunciation_scores.append(item["pronunciation_metrics"]["pronunciation_formula_score"])

    return {
        "total_answers": total_answers,
        "total_words": total_words,
        "total_speaking_duration_seconds": round(total_duration, 2),
        "average_words_per_minute": round(float(np.mean(wpms)), 2) if len(wpms) > 0 else 0.0,
        "empty_answer_count": empty_answer_count,
        "short_answer_count": short_answer_count,
        "total_pause_count": total_pause_count,
        "total_filler_count": total_filler_count,
        "total_repetition_count": total_repetition_count,
        "average_silent_ratio": round(float(np.mean(silent_ratios)), 3) if len(silent_ratios) > 0 else 1.0,
        "average_speech_ratio": round(float(np.mean(speech_ratios)), 3) if len(speech_ratios) > 0 else 0.0,
        "formula_scores_01": {
            "fluency_and_coherence": round(float(np.mean(fluency_scores)), 3) if len(fluency_scores) > 0 else 0.0,
            "lexical_resource": round(float(np.mean(lexical_scores)), 3) if len(lexical_scores) > 0 else 0.0,
            "grammatical_range_and_accuracy": round(float(np.mean(grammar_scores)), 3) if len(grammar_scores) > 0 else 0.0,
            "pronunciation": round(float(np.mean(pronunciation_scores)), 3) if len(pronunciation_scores) > 0 else 0.0
        }
    }


