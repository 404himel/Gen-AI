def enrich_items_for_advanced_evaluation(answer_items, number_of_high_band_answers=3):
    enriched_items = []
    reference_items = []

    for item in answer_items:
        print("Generating high band answers for:", item["question"][:80])

        high_band_answers = generate_high_band_answers(
            question=item["question"],
            part=item["part"],
            item_type=item["item_type"],
            number_of_answers=number_of_high_band_answers
        )

        reference_items.append({
            "part": item["part"],
            "item_type": item["item_type"],
            "question": item["question"],
            "high_band_answers": high_band_answers
        })

        audio_features = extract_audio_features(
            audio_path=item["answer_audio"],
            transcript=item["answer_text"]
        )

        fluency_metrics = fluency_formula_score(
            audio_features=audio_features,
            user_answer=item["answer_text"],
            reference_answers=high_band_answers
        )

        lexical_result = lexical_metrics(
            user_answer=item["answer_text"],
            reference_answers=high_band_answers
        )

        grammar_result = grammar_metrics(
            user_answer=item["answer_text"]
        )

        pronunciation_result = pronunciation_formula_score(
            audio_features=audio_features
        )

        enriched_item = item.copy()
        enriched_item["high_band_answers"] = high_band_answers
        enriched_item["audio_features"] = audio_features
        enriched_item["fluency_metrics"] = fluency_metrics
        enriched_item["lexical_metrics"] = lexical_result
        enriched_item["grammar_metrics"] = grammar_result
        enriched_item["pronunciation_metrics"] = pronunciation_result
        enriched_item["word_count"] = count_words(item["answer_text"])

        enriched_items.append(enriched_item)

    save_high_band_answers(
        reference_items=reference_items,
        file_path="ielts_high_band_reference_answers.txt"
    )

    return enriched_items, reference_items


