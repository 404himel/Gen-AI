def clean_cue_card(text):
    text = str(text).strip()
    text = text.replace("Cue Card:", "").strip()

    if len(text) < 20:
        return None

    return text


def generate_part2_cue_card():
    prompt = """
You are an IELTS Speaking examiner.

Generate one IELTS Speaking Part 2 cue card.

Rules:
Return only the cue card.
Use this format exactly:

Describe ...
You should say:
who or what it is
when or where it happened
what happened
and explain why it was important to you

The topic should be familiar and suitable for IELTS Speaking Part 2.
Do not explain anything.

Cue Card:
"""

    result = llm(
        prompt,
        max_new_tokens=180,
        do_sample=True,
        temperature=0.7,
        top_p=0.9
    )

    generated_text = result[0]["generated_text"]
    cue_card = generated_text[len(prompt):].strip()
    cue_card = clean_cue_card(cue_card)

    if cue_card is None:
        cue_card = """
Describe a place you visited recently.
You should say:
where it was
when you went there
who you went with
and explain why you liked it
"""

    return cue_card

