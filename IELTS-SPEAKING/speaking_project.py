def build_llm_descriptor_input(enriched_items, global_features):
    text = "IELTS Speaking Candidate Data\n"
    text += "=" * 70 + "\n\n"

    current_part = None

    for item in enriched_items:
        if item["part"] != current_part:
            current_part = item["part"]
            text += f"\n{current_part}\n"
            text += "=" * 40 + "\n"

        text += f"Item Type: {item['item_type']}\n"
        text += f"Question: {item['question']}\n"
        text += f"Candidate Answer: {item['answer_text']}\n"
        text += f"Word Count: {item['word_count']}\n"
        text += f"Audio Features: {json.dumps(item['audio_features'])}\n"
        text += f"Fluency Formula Metrics: {json.dumps(item['fluency_metrics'])}\n"
        text += f"Lexical Metrics: {json.dumps(item['lexical_metrics'])}\n"
        text += f"Grammar Metrics: {json.dumps(item['grammar_metrics'])}\n"
        text += f"Pronunciation Metrics: {json.dumps(item['pronunciation_metrics'])}\n\n"

    text += "\nGlobal Features\n"
    text += "=" * 40 + "\n"
    text += json.dumps(global_features, indent=2)

    return text


def get_llm_band_descriptor_scores(enriched_items, global_features, evidence_cap, cap_reasons):
    evaluator = get_generation_model()
    llm_input = build_llm_descriptor_input(enriched_items, global_features)

    prompt = f"""
You are a strict IELTS Speaking evaluator.

Evaluate the full speaking performance using IELTS Speaking band descriptor logic.

Important:
Do not score Part 1, Part 2, and Part 3 separately.
Give one score for each criterion only.
Use these four criteria:
Fluency and Coherence
Lexical Resource
Grammatical Range and Accuracy
Pronunciation

Use the measured evidence.
Be strict.
Do not give high scores for empty, short, incomplete, or unclear answers.
Evidence based maximum possible band is:
{evidence_cap}

Reasons for this maximum:
{json.dumps(cap_reasons, indent=2)}

Candidate data:
{llm_input}

Return only valid JSON.

JSON format:
{{
  "band_descriptor_scores": {{
    "fluency_and_coherence": number,
    "lexical_resource": number,
    "grammatical_range_and_accuracy": number,
    "pronunciation": number
  }},
  "detailed_description": {{
    "fluency_and_coherence": "detailed explanation",
    "lexical_resource": "detailed explanation",
    "grammatical_range_and_accuracy": "detailed explanation",
    "pronunciation": "detailed explanation"
  }},
  "overall_comment": "short overall comment"
}}
"""

    try:
        result = evaluator(
            prompt,
            max_new_tokens=900,
            do_sample=False,
            temperature=0.1,
            top_p=0.9,
            return_full_text=False
        )

        response = result[0]["generated_text"].strip()
        data = extract_json(response)

        if data is not None:
            return data

    except:
        pass

    return {
        "band_descriptor_scores": {
            "fluency_and_coherence": evidence_cap,
            "lexical_resource": evidence_cap,
            "grammatical_range_and_accuracy": evidence_cap,
            "pronunciation": evidence_cap
        },
        "detailed_description": {
            "fluency_and_coherence": "The score is based on measured fluency evidence and transcript structure.",
            "lexical_resource": "The score is based on vocabulary range and reference answer comparison.",
            "grammatical_range_and_accuracy": "The score is based on grammar accuracy and sentence complexity.",
            "pronunciation": "The score is based on audio clarity, speech continuity, and transcript clarity."
        },
        "overall_comment": "The score was produced using measured evidence and IELTS style criteria."
    }


