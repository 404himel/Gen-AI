import re

def load_part1_records_from_txt(file_path="ielts_part1_question_answers.txt"):
    records = []

    with open(file_path, "r", encoding="utf-8") as f:
        content = f.read()

    blocks = content.split("=" * 60)

    for block in blocks:
        block = block.strip()

        if "Question" not in block or "User Answer Transcript:" not in block:
            continue

        question_number_match = re.search(
            r"Question\s+(\d+):",
            block
        )

        question_match = re.search(
            r"Question\s+\d+:\s*(.*?)\n\nUser Answer Transcript:",
            block,
            re.DOTALL
        )

        answer_match = re.search(
            r"User Answer Transcript:\s*(.*?)\n\nAnswer Time Limit:",
            block,
            re.DOTALL
        )

        time_match = re.search(
            r"Answer Time Limit:\s*(\d+)",
            block
        )

        question_number = int(question_number_match.group(1)) if question_number_match else len(records) + 1
        question = question_match.group(1).strip() if question_match else ""
        answer_text = answer_match.group(1).strip() if answer_match else ""
        time_limit = int(time_match.group(1)) if time_match else 0

        records.append({
            "part": "Part 1",
            "question_number": question_number,
            "item_type": "Question",
            "question": question,
            "answer_audio": f"part1_answer_{question_number}.webm",
            "answer_text": answer_text,
            "time_limit": time_limit,
            "is_empty_answer": is_empty_answer(answer_text)
        })

    return records


