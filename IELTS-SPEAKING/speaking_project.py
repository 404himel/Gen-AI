def convert_audio_to_wav(input_path, output_path):
    if input_path is None or input_path == "":
        return None

    if not os.path.exists(input_path):
        return None

    command = f'ffmpeg -y -i "{input_path}" -ac 1 -ar 16000 "{output_path}" -loglevel quiet'
    os.system(command)

    if os.path.exists(output_path):
        return output_path

    return None


def extract_audio_features(audio_path, transcript=""):
    features = {
        "audio_file": audio_path,
        "duration_seconds": 0.0,
        "word_count": count_words(transcript),
        "words_per_minute": 0.0,
        "words_per_second": 0.0,
        "speech_ratio": 0.0,
        "silent_ratio": 1.0,
        "pause_count": 0,
        "average_pause_seconds": 0.0,
        "long_pause_count": 0,
        "filler_count": 0,
        "repetition_count": 0,
        "energy_mean": 0.0,
        "energy_std": 0.0,
        "clarity_proxy": 0.0
    }

    transcript = safe_text(transcript)
    lower_text = transcript.lower()

    fillers = [
        "um",
        "uh",
        "erm",
        "er",
        "you know",
        "i mean"
    ]

    filler_count = 0

    for filler in fillers:
        filler_count += lower_text.count(filler)

    features["filler_count"] = filler_count

    words = clean_text_for_words(transcript)
    repetition_count = 0

    for i in range(1, len(words)):
        if words[i] == words[i - 1]:
            repetition_count += 1

    features["repetition_count"] = repetition_count

    if audio_path is None or audio_path == "" or not os.path.exists(audio_path):
        return features

    wav_path = audio_path

    if not audio_path.lower().endswith(".wav"):
        wav_path = audio_path.rsplit(".", 1)[0] + "_eval.wav"
        wav_path = convert_audio_to_wav(audio_path, wav_path)

        if wav_path is None:
            return features

    try:
        y, sr = librosa.load(wav_path, sr=16000, mono=True)
    except:
        return features

    duration = librosa.get_duration(y=y, sr=sr)
    features["duration_seconds"] = round(float(duration), 2)

    if duration > 0:
        features["words_per_minute"] = round((features["word_count"] / duration) * 60, 2)
        features["words_per_second"] = round(features["word_count"] / duration, 2)

    intervals = librosa.effects.split(y, top_db=30)

    speech_duration = 0.0

    for start, end in intervals:
        speech_duration += (end - start) / sr

    if duration > 0:
        speech_ratio = speech_duration / duration
        features["speech_ratio"] = round(float(speech_ratio), 3)
        features["silent_ratio"] = round(float(1.0 - speech_ratio), 3)

    pauses = []

    if len(intervals) > 1:
        for i in range(1, len(intervals)):
            previous_end = intervals[i - 1][1]
            current_start = intervals[i][0]
            pause_duration = (current_start - previous_end) / sr

            if pause_duration >= 0.35:
                pauses.append(pause_duration)

    features["pause_count"] = len(pauses)

    if len(pauses) > 0:
        features["average_pause_seconds"] = round(float(np.mean(pauses)), 2)

    features["long_pause_count"] = len([p for p in pauses if p >= 1.0])

    rms = librosa.feature.rms(y=y)[0]

    if len(rms) > 0:
        energy_mean = float(np.mean(rms))
        energy_std = float(np.std(rms))

        features["energy_mean"] = round(energy_mean, 5)
        features["energy_std"] = round(energy_std, 5)

        if energy_mean > 0:
            clarity_proxy = 1.0 - min(energy_std / (energy_mean + 1e-8), 1.0)
            features["clarity_proxy"] = round(float(max(0.0, clarity_proxy)), 3)

    return features


